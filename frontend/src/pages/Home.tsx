function CategoryTiles({ items }: { items: ProductListItem[] }) {
  const categories = useMemo(() => {
    const map = new Map<string, ProductListItem[]>();
    items.forEach((p) => map.set(p.category, [...(map.get(p.category) ?? []), p]));
    return [...map.entries()].sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]));
  }, [items]);
  if (categories.length === 0) return null;
  return (
    <div className="no-scrollbar -mx-4 flex snap-x gap-4 overflow-x-auto px-4 pb-2 sm:mx-0 sm:grid sm:grid-cols-3 sm:overflow-visible sm:px-0 lg:grid-cols-6">
      {categories.map(([category, products]) => (
        <Link
          key={category}
          to={`/shop?category=${encodeURIComponent(category)}`}
          className="group relative w-40 shrink-0 snap-start overflow-hidden rounded-card bg-canvas sm:w-auto"
        >
          <ProductImage src={products[0].thumbnail_url} alt="" className="aspect-[3/4] w-full transition-transform duration-700 group-hover:scale-105" />
          <span className="absolute inset-x-0 bottom-0 bg-gradient-to-t from-ink/70 to-transparent px-4 pb-3.5 pt-10 text-ivory">
            <span className="block font-display text-lg leading-tight">{category}</span>
            <span className="text-xs text-ivory/80">
              {products.length} {products.length === 1 ? "style" : "styles"}
            </span>
          </span>
        </Link>
      ))}
    </div>
  );
}

